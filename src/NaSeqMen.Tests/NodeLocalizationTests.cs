namespace NaSeqMen.Tests;

internal static class NodeLocalizationTests
{
    public static IReadOnlyList<(string Name, Func<Task> Run)> GetTests() =>
    [
        ("1. All 18 nodes have EN and RU catalogs and Markdown docs", TestAll18NodesEnRuAsync),
        ("2. Embedded resources work without external disk folders", TestEmbeddedFallbackAsync),
        ("3. External override takes priority and discovers new language without rebuild", TestExternalOverrideAndDynamicLangAsync),
        ("4. Third-party plugin without locales gets auto-generated Markdown", TestThirdPartyAutoDocsAsync),
    ];

    private sealed class ThirdPartyNoLocaleNode : NodeBase
    {
        public static readonly NodeTypeDescriptor TypeDescriptor = new()
        {
            TypeId = "thirdparty.custom-widget",
            DisplayName = "Custom Third-Party Node",
            Category = "ThirdParty",
            Description = "A third-party node shipped with zero localization or Markdown docs.",
            Inputs = [new PortDefinition { Id = "in", Label = "Signal", Direction = PortDirection.Input, DataType = PortDataType.Any }],
            Outputs = [new PortDefinition { Id = "out", Label = "Result", Direction = PortDirection.Output, DataType = PortDataType.String }],
            Parameters = [new ParameterDefinition { Key = "gain", Label = "Gain", Kind = ParameterKind.Number, DefaultValue = 1.5, Description = "Signal multiplier." }],
        };

        public override NodeTypeDescriptor Descriptor => TypeDescriptor;
        public override Task OnInputAsync(string inputPortId, FlowMessage message, CancellationToken cancellationToken) => Task.CompletedTask;
    }

    private static NodeRegistry CreateFullRegistry()
    {
        var reg = new NodeRegistry();
        reg.RegisterPlugin(new BasicNodesPlugin(), "built-in");
        reg.RegisterPlugin(new ControlsNodesPlugin(), "built-in");
        reg.RegisterPlugin(new ScriptingNodesPlugin(), "built-in");
        reg.RegisterPlugin(new InterceptionNodesPlugin(), "plugin");
        reg.RegisterPlugin(new ObsNodesPlugin(), "plugin");
        reg.RegisterPlugin(new WindowsNodesPlugin(), "plugin");
        return reg;
    }

    private static Task TestAll18NodesEnRuAsync()
    {
        var reg = CreateFullRegistry();
        var srcRoot = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", ".."));
        var svc = new NodeLocalizationService(reg, AppContext.BaseDirectory, srcRoot);

        var langs = svc.GetAvailableLanguages();
        Assert.True(langs.Any(l => l.Code == "en"), "Available languages must include 'en'");
        Assert.True(langs.Any(l => l.Code == "ru"), "Available languages must include 'ru'");

        var enCatalog = svc.GetLocalizedCatalog("en");
        var ruCatalog = svc.GetLocalizedCatalog("ru");
        Assert.Equal(18, enCatalog.Count);
        Assert.Equal(18, ruCatalog.Count);

        var ruSwitch = ruCatalog.Single(d => d.TypeId == "interception.hotkey-switch");
        Assert.True(ruSwitch.DisplayName != "Hotkey Switch", "Expected RU displayName for interception.hotkey-switch");
        Assert.True(ruSwitch.Parameters.Single(p => p.Key == "rules").Label != "Hotkey Rules", "Expected RU label for 'rules'");

        var ruObs = ruCatalog.Single(d => d.TypeId == "obs.studio");
        Assert.True(ruObs.Parameters.Single(p => p.Key == "enabled").Label != "Connect", "Expected RU label for OBS 'enabled'");

        foreach (var desc in enCatalog)
        {
            var enDoc = svc.GetNodeDocumentation(desc.TypeId, "en");
            Assert.NotNull(enDoc, $"EN doc should exist for {desc.TypeId}");
            Assert.True(!enDoc!.IsAutoGenerated, $"Missing EN .md for {desc.TypeId}");
            Assert.True(!enDoc.IsFallback, $"Unexpected fallback for EN {desc.TypeId}");
            Assert.True(enDoc.Markdown.Length > 100, $"Too short EN .md for {desc.TypeId}");

            var ruDoc = svc.GetNodeDocumentation(desc.TypeId, "ru");
            Assert.NotNull(ruDoc, $"RU doc should exist for {desc.TypeId}");
            Assert.True(!ruDoc!.IsAutoGenerated, $"Missing RU .md for {desc.TypeId}");
            Assert.True(!ruDoc.IsFallback, $"Unexpected fallback for RU {desc.TypeId}");
            Assert.True(ruDoc.Markdown.Length > 100, $"Too short RU .md for {desc.TypeId}");
        }

        // Also verify staged Host output has external locales folders for plugins and built-ins
        var hostBin = Path.Combine(srcRoot, "NaSeqMen.Host", "bin", "Debug", "net11.0-windows");
        Assert.True(File.Exists(Path.Combine(hostBin, "plugins", "NaSeqMen.Nodes.Interception", "locales", "ru", "interception.hotkey-switch.md")),
            "Expected staged external RU doc in plugins/NaSeqMen.Nodes.Interception/locales/ru/");
        Assert.True(File.Exists(Path.Combine(hostBin, "locales", "NaSeqMen.Nodes.Basic", "ru", "strings.json")),
            "Expected staged built-in RU strings.json in locales/NaSeqMen.Nodes.Basic/ru/");

        return Task.CompletedTask;
    }

    private static Task TestEmbeddedFallbackAsync()
    {
        var reg = CreateFullRegistry();
        var emptyDir = Path.Combine(Path.GetTempPath(), "naseqmen-loc-empty-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(emptyDir);
        try
        {
            var svc = new NodeLocalizationService(reg, emptyDir, devProjectsRoot: null);
            var doc = svc.GetNodeDocumentation("interception.hotkey-switch", "ru");

            Assert.NotNull(doc, "Embedded RU doc should load");
            Assert.Equal("embedded", doc!.Source);
            Assert.True(!doc.IsAutoGenerated, "Embedded RU doc should not be auto-generated");
            Assert.Equal("ru", doc.ResolvedLang);
        }
        finally
        {
            Directory.Delete(emptyDir, recursive: true);
        }

        return Task.CompletedTask;
    }

    private static Task TestExternalOverrideAndDynamicLangAsync()
    {
        var reg = CreateFullRegistry();
        var tempAppDir = Path.Combine(Path.GetTempPath(), "naseqmen-loc-override-" + Guid.NewGuid().ToString("N"));
        var deDir = Path.Combine(tempAppDir, "locales-override", "de");
        Directory.CreateDirectory(deDir);
        try
        {
            File.WriteAllText(Path.Combine(deDir, "basic.debug.md"), "# Debug (Deutsch)\nBenutzerdefinierte Dokumentation.");
            var svc = new NodeLocalizationService(reg, tempAppDir, devProjectsRoot: null);

            var langs = svc.GetAvailableLanguages();
            Assert.True(langs.Any(l => l.Code == "de"), "Dynamically dropped 'de' folder should be discovered");

            var deDoc = svc.GetNodeDocumentation("basic.debug", "de");
            Assert.NotNull(deDoc, "German override doc should load");
            Assert.Equal("override", deDoc!.Source);
            Assert.Equal("de", deDoc.ResolvedLang);
            Assert.True(!deDoc.IsFallback, "Exact 'de' override should not be marked fallback");
            Assert.True(deDoc.Markdown.Contains("Benutzerdefinierte Dokumentation", StringComparison.Ordinal), "Expected German text");

            var fallbackDoc = svc.GetNodeDocumentation("basic.to-upper", "de");
            Assert.NotNull(fallbackDoc, "Fallback EN doc should load for missing German file");
            Assert.True(fallbackDoc!.IsFallback, "Missing 'de' doc should fall back to 'en'");
            Assert.Equal("en", fallbackDoc.ResolvedLang);
        }
        finally
        {
            Directory.Delete(tempAppDir, recursive: true);
        }

        return Task.CompletedTask;
    }

    private static Task TestThirdPartyAutoDocsAsync()
    {
        var reg = new NodeRegistry();
        reg.Register(() => new ThirdPartyNoLocaleNode(), pluginId: "thirdparty.plugin", source: "plugin");

        var tempAppDir = Path.Combine(Path.GetTempPath(), "naseqmen-loc-3p-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempAppDir);
        try
        {
            var svc = new NodeLocalizationService(reg, tempAppDir, devProjectsRoot: null);
            var catalog = svc.GetLocalizedCatalog("ru");
            Assert.Equal(1, catalog.Count);
            Assert.Equal("Custom Third-Party Node", catalog[0].DisplayName);

            var doc = svc.GetNodeDocumentation("thirdparty.custom-widget", "ru");
            Assert.NotNull(doc, "Auto-generated doc should be returned for third-party node");
            Assert.True(doc!.IsAutoGenerated, "Third-party node without .md should return auto-generated docs");
            Assert.True(doc.Markdown.Contains("Custom Third-Party Node", StringComparison.Ordinal), "Auto doc should contain node name");
            Assert.True(doc.Markdown.Contains("Gain", StringComparison.Ordinal), "Auto doc should contain parameter label");
            Assert.True(doc.Markdown.Contains("Signal", StringComparison.Ordinal), "Auto doc should contain port label");
        }
        finally
        {
            Directory.Delete(tempAppDir, recursive: true);
        }

        return Task.CompletedTask;
    }
}
