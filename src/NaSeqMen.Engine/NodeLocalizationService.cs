using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using NaSeqMen.Core.Nodes;

namespace NaSeqMen.Engine;

public sealed record AvailableLanguageInfo(string Code, string NativeName);

public sealed record NodeDocumentationResult(
    string TypeId,
    string RequestedLang,
    string ResolvedLang,
    bool IsFallback,
    bool IsAutoGenerated,
    string Title,
    string Category,
    string Markdown,
    string Source);

/// <summary>
/// Hybrid N-language localization and Markdown documentation provider for built-in modules
/// and dynamically loaded plugins.
///
/// Lookup priority (highest to lowest):
/// 1. Runtime override folder: &lt;AppBase&gt;/locales-override/&lt;lang&gt;/...
/// 2. Dev source folder (when running from source): &lt;DevRoot&gt;/&lt;AssemblyName&gt;/locales/&lt;lang&gt;/...
/// 3. Deployed plugin/module disk folder: &lt;PluginDir&gt;/locales/&lt;lang&gt;/... or &lt;AppBase&gt;/locales/&lt;AssemblyName&gt;/&lt;lang&gt;/...
/// 4. Embedded resources inside the plugin Assembly (fallback for single-DLL third-party plugins)
/// 5. Fallback language ("en") -&gt; raw C# NodeTypeDescriptor (auto-generated Markdown if no .md exists)
/// </summary>
public sealed class NodeLocalizationService
{
    private static readonly JsonSerializerOptions JsonOpts = new()
    {
        PropertyNameCaseInsensitive = true,
        ReadCommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true,
    };

    private readonly NodeRegistry _registry;
    private readonly string _appBaseDir;
    private readonly string? _devProjectsRoot;

    public NodeLocalizationService(NodeRegistry registry, string appBaseDirectory, string? devProjectsRoot = null)
    {
        _registry = registry;
        _appBaseDir = appBaseDirectory;
        _devProjectsRoot = string.IsNullOrWhiteSpace(devProjectsRoot) ? null : Path.GetFullPath(devProjectsRoot);
    }

    public IReadOnlyList<AvailableLanguageInfo> GetAvailableLanguages()
    {
        var codes = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "en" };

        CollectDirLanguages(Path.Combine(_appBaseDir, "locales-override"), codes);

        var visitedAssemblies = new HashSet<Assembly>();
        foreach (var reg in _registry.GetRegistrations())
        {
            if (!visitedAssemblies.Add(reg.Assembly))
                continue;

            foreach (var root in GetLocaleRoots(reg))
            {
                CollectDirLanguages(root, codes);
            }

            CollectEmbeddedLanguages(reg.Assembly, codes);
        }

        return codes
            .Select(NormalizeLang)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(c => c.Equals("en", StringComparison.OrdinalIgnoreCase) ? 0 : c.Equals("ru", StringComparison.OrdinalIgnoreCase) ? 1 : 2)
            .ThenBy(c => c, StringComparer.OrdinalIgnoreCase)
            .Select(code => new AvailableLanguageInfo(code, GetNativeLanguageName(code)))
            .ToArray();
    }

    public IReadOnlyList<NodeTypeDescriptor> GetLocalizedCatalog(string? requestedLang)
    {
        var langChain = BuildLangFallbackChain(requestedLang);
        var bundleCache = new Dictionary<(Assembly, string), LocaleStringsBundle?>();

        var result = new List<NodeTypeDescriptor>();
        foreach (var reg in _registry.GetRegistrations())
        {
            var localized = LocalizeDescriptor(reg, langChain, bundleCache);
            result.Add(localized);
        }

        return result
            .OrderBy(d => d.Category, StringComparer.OrdinalIgnoreCase)
            .ThenBy(d => d.DisplayName, StringComparer.OrdinalIgnoreCase)
            .ToArray();
    }

    public NodeDocumentationResult? GetNodeDocumentation(string typeId, string? requestedLang)
    {
        if (!_registry.TryGetRegistration(typeId, out var reg))
            return null;

        var reqLang = NormalizeLang(requestedLang);
        var langChain = BuildLangFallbackChain(reqLang);
        var bundleCache = new Dictionary<(Assembly, string), LocaleStringsBundle?>();
        var localizedDesc = LocalizeDescriptor(reg, langChain, bundleCache);

        var docFileName = $"{typeId}.md";
        foreach (var candidateLang in langChain)
        {
            var (content, source) = TryReadTextAsset(reg, candidateLang, docFileName);
            if (!string.IsNullOrWhiteSpace(content))
            {
                var isFallback = !candidateLang.Equals(reqLang, StringComparison.OrdinalIgnoreCase);
                return new NodeDocumentationResult(
                    TypeId: typeId,
                    RequestedLang: reqLang,
                    ResolvedLang: candidateLang,
                    IsFallback: isFallback,
                    IsAutoGenerated: false,
                    Title: localizedDesc.DisplayName,
                    Category: localizedDesc.Category,
                    Markdown: content,
                    Source: source);
            }
        }

        // Graceful fallback for third-party plugins without Markdown docs
        var autoMd = BuildAutoGeneratedMarkdown(localizedDesc, reqLang);
        return new NodeDocumentationResult(
            TypeId: typeId,
            RequestedLang: reqLang,
            ResolvedLang: reqLang,
            IsFallback: true,
            IsAutoGenerated: true,
            Title: localizedDesc.DisplayName,
            Category: localizedDesc.Category,
            Markdown: autoMd,
            Source: "auto-descriptor");
    }

    private NodeTypeDescriptor LocalizeDescriptor(
        NodeRegistrationInfo reg,
        IReadOnlyList<string> langChain,
        Dictionary<(Assembly, string), LocaleStringsBundle?> bundleCache)
    {
        var baseDesc = reg.Descriptor;
        // Load bundles in priority order (most specific first; e.g. ["ru", "en"])
        var bundles = new List<LocaleStringsBundle>();
        foreach (var lang in langChain)
        {
            var key = (reg.Assembly, lang);
            if (!bundleCache.TryGetValue(key, out var bundle))
            {
                bundle = TryLoadStringsBundle(reg, lang);
                bundleCache[key] = bundle;
            }
            if (bundle is not null)
                bundles.Add(bundle);
        }

        if (bundles.Count == 0)
            return baseDesc;

        string? PickCategory(string rawCategory)
        {
            foreach (var b in bundles)
            {
                if (b.Categories is not null && b.Categories.TryGetValue(rawCategory, out var translated) && !string.IsNullOrWhiteSpace(translated))
                    return translated;
            }
            return null;
        }

        var nodeEntries = bundles
            .Select(b => b.Nodes is not null && b.Nodes.TryGetValue(baseDesc.TypeId, out var ne) ? ne : null)
            .Where(ne => ne is not null)
            .Cast<NodeLocaleEntry>()
            .ToList();

        var displayName = nodeEntries.Select(e => e.DisplayName).FirstOrDefault(s => !string.IsNullOrWhiteSpace(s))
            ?? baseDesc.DisplayName;
        var category = PickCategory(baseDesc.Category) ?? baseDesc.Category;
        var description = nodeEntries.Select(e => e.Description).FirstOrDefault(s => !string.IsNullOrWhiteSpace(s))
            ?? baseDesc.Description;

        PortDefinition LocalizePort(PortDefinition port)
        {
            string? lbl = null;
            string? desc = null;
            foreach (var ne in nodeEntries)
            {
                if (ne.Ports is null || !ne.Ports.TryGetValue(port.Id, out var pe))
                    continue;
                lbl ??= string.IsNullOrWhiteSpace(pe.Label) ? null : pe.Label;
                desc ??= string.IsNullOrWhiteSpace(pe.Description) ? null : pe.Description;
            }
            if (lbl is null && desc is null)
                return port;

            return port with
            {
                Label = lbl ?? port.Label,
                Description = desc ?? port.Description,
            };
        }

        ParameterDefinition LocalizeParam(ParameterDefinition param)
        {
            string? lbl = null;
            string? desc = null;
            string? placeholder = null;
            Dictionary<string, string>? mergedOptions = null;

            foreach (var ne in nodeEntries)
            {
                if (ne.Parameters is null || !ne.Parameters.TryGetValue(param.Key, out var pe))
                    continue;
                lbl ??= string.IsNullOrWhiteSpace(pe.Label) ? null : pe.Label;
                desc ??= string.IsNullOrWhiteSpace(pe.Description) ? null : pe.Description;
                placeholder ??= string.IsNullOrWhiteSpace(pe.Placeholder) ? null : pe.Placeholder;

                if (pe.Options is not null && param.Options is not null)
                {
                    mergedOptions ??= new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                    foreach (var (ok, ov) in pe.Options)
                    {
                        if (!string.IsNullOrWhiteSpace(ov) && !mergedOptions.ContainsKey(ok))
                            mergedOptions[ok] = ov;
                    }
                }
            }

            if (lbl is null && desc is null && placeholder is null && mergedOptions is null)
                return param;

            IReadOnlyList<ParameterOption>? newOptions = param.Options;
            if (mergedOptions is not null && param.Options is not null)
            {
                newOptions = param.Options
                    .Select(opt => mergedOptions.TryGetValue(opt.Value, out var oLbl) ? new ParameterOption(opt.Value, oLbl) : opt)
                    .ToArray();
            }

            return param with
            {
                Label = lbl ?? param.Label,
                Description = desc ?? param.Description,
                Placeholder = placeholder ?? param.Placeholder,
                Options = newOptions,
            };
        }

        return baseDesc with
        {
            DisplayName = displayName,
            Category = category,
            Description = description,
            Inputs = baseDesc.Inputs.Select(LocalizePort).ToArray(),
            Outputs = baseDesc.Outputs.Select(LocalizePort).ToArray(),
            Parameters = baseDesc.Parameters.Select(LocalizeParam).ToArray(),
        };
    }

    private LocaleStringsBundle? TryLoadStringsBundle(NodeRegistrationInfo reg, string lang)
    {
        var (json, _) = TryReadTextAsset(reg, lang, "strings.json");
        if (string.IsNullOrWhiteSpace(json))
            return null;

        try
        {
            return JsonSerializer.Deserialize<LocaleStringsBundle>(json, JsonOpts);
        }
        catch
        {
            return null;
        }
    }

    private (string? Content, string Source) TryReadTextAsset(NodeRegistrationInfo reg, string lang, string fileName)
    {
        // 1. User / runtime override folder: <AppBase>/locales-override/<lang>/<fileName>
        var overridePath = Path.Combine(_appBaseDir, "locales-override", lang, fileName);
        if (File.Exists(overridePath))
            return (TryReadFileUtf8(overridePath), "override");

        // 2 & 3. Dev source folder, then deployed plugin / module folder
        foreach (var root in GetLocaleRoots(reg))
        {
            var candidate = Path.Combine(root, lang, fileName);
            if (File.Exists(candidate))
                return (TryReadFileUtf8(candidate), "disk");
        }

        // 4. Embedded resource fallback inside plugin/module Assembly
        var embedded = TryReadEmbeddedResource(reg.Assembly, lang, fileName);
        if (embedded is not null)
            return (embedded, "embedded");

        return (null, "none");
    }

    private IEnumerable<string> GetLocaleRoots(NodeRegistrationInfo reg)
    {
        var asmName = reg.Assembly.GetName().Name ?? reg.PluginId;

        // Dev source root first so editing .md / strings.json works live without rebuilding
        if (_devProjectsRoot is not null)
        {
            var devDir = Path.Combine(_devProjectsRoot, asmName, "locales");
            if (Directory.Exists(devDir))
                yield return devDir;
        }

        // Deployed external plugin folder: <PluginDir>/locales
        if (!string.IsNullOrWhiteSpace(reg.AssemblyPath))
        {
            var pluginDir = Path.GetDirectoryName(reg.AssemblyPath);
            if (!string.IsNullOrWhiteSpace(pluginDir))
            {
                var pluginLocales = Path.Combine(pluginDir, "locales");
                if (Directory.Exists(pluginLocales))
                    yield return pluginLocales;
            }
        }

        // Deployed built-in module folder: <AppBase>/locales/<AssemblyName>
        var builtInDir = Path.Combine(_appBaseDir, "locales", asmName);
        if (Directory.Exists(builtInDir))
            yield return builtInDir;
    }

    private static string? TryReadEmbeddedResource(Assembly assembly, string lang, string fileName)
    {
        var slashSuffix = $"locales/{lang}/{fileName}";
        var dotSuffix = $".locales.{lang}.{fileName}";

        foreach (var resName in assembly.GetManifestResourceNames())
        {
            var normalized = resName.Replace('\\', '/');
            if (normalized.Equals(slashSuffix, StringComparison.OrdinalIgnoreCase) ||
                normalized.EndsWith("/" + slashSuffix, StringComparison.OrdinalIgnoreCase) ||
                resName.EndsWith(dotSuffix, StringComparison.OrdinalIgnoreCase))
            {
                using var stream = assembly.GetManifestResourceStream(resName);
                if (stream is null) continue;
                using var reader = new StreamReader(stream, Encoding.UTF8);
                return reader.ReadToEnd();
            }
        }

        return null;
    }

    private static void CollectDirLanguages(string localesRoot, HashSet<string> codes)
    {
        if (!Directory.Exists(localesRoot))
            return;

        foreach (var dir in Directory.GetDirectories(localesRoot))
        {
            var name = Path.GetFileName(dir);
            if (IsPlausibleLangCode(name))
                codes.Add(name.ToLowerInvariant());
        }
    }

    private static void CollectEmbeddedLanguages(Assembly assembly, HashSet<string> codes)
    {
        foreach (var resName in assembly.GetManifestResourceNames())
        {
            var norm = resName.Replace('\\', '/');
            var idx = norm.IndexOf("locales/", StringComparison.OrdinalIgnoreCase);
            if (idx >= 0)
            {
                var rest = norm[(idx + "locales/".Length)..];
                var slash = rest.IndexOf('/');
                if (slash > 0)
                {
                    var code = rest[..slash];
                    if (IsPlausibleLangCode(code))
                        codes.Add(code.ToLowerInvariant());
                }
            }
        }
    }

    private static bool IsPlausibleLangCode(string? value)
    {
        if (string.IsNullOrWhiteSpace(value) || value.Length < 2 || value.Length > 10)
            return false;

        foreach (var ch in value)
        {
            if (!char.IsLetter(ch) && ch != '-')
                return false;
        }
        return true;
    }

    private static string? TryReadFileUtf8(string path)
    {
        try
        {
            return File.ReadAllText(path, Encoding.UTF8);
        }
        catch
        {
            return null;
        }
    }

    private static IReadOnlyList<string> BuildLangFallbackChain(string? requestedLang)
    {
        var list = new List<string>(3);
        var norm = NormalizeLang(requestedLang);
        list.Add(norm);

        var dash = norm.IndexOf('-');
        if (dash > 0)
        {
            var baseLang = norm[..dash];
            if (!list.Any(x => x.Equals(baseLang, StringComparison.OrdinalIgnoreCase)))
                list.Add(baseLang);
        }

        if (!list.Any(x => x.Equals("en", StringComparison.OrdinalIgnoreCase)))
            list.Add("en");

        return list;
    }

    private static string NormalizeLang(string? lang)
    {
        if (string.IsNullOrWhiteSpace(lang))
            return "en";

        var clean = lang.Trim().Replace('_', '-').ToLowerInvariant();
        return IsPlausibleLangCode(clean) ? clean : "en";
    }

    private static string GetNativeLanguageName(string code)
    {
        try
        {
            var ci = CultureInfo.GetCultureInfo(code);
            var native = ci.NativeName;
            if (!string.IsNullOrWhiteSpace(native))
                return char.ToUpper(native[0], ci) + native[1..];
        }
        catch
        {
            // unknown culture code
        }

        return code.ToUpperInvariant();
    }

    private static string BuildAutoGeneratedMarkdown(NodeTypeDescriptor desc, string lang)
    {
        var isRu = lang.StartsWith("ru", StringComparison.OrdinalIgnoreCase);
        var sb = new StringBuilder();
        sb.AppendLine($"# {desc.DisplayName}");
        sb.AppendLine();
        if (!string.IsNullOrWhiteSpace(desc.Description))
        {
            sb.AppendLine(desc.Description);
            sb.AppendLine();
        }

        if (desc.Inputs.Count > 0)
        {
            sb.AppendLine(isRu ? "## Входы" : "## Inputs");
            foreach (var p in desc.Inputs)
                sb.AppendLine($"- **`{p.Label}`** (`{p.DataType}`) — {p.Description ?? "—"}");
            sb.AppendLine();
        }

        if (desc.Outputs.Count > 0)
        {
            sb.AppendLine(isRu ? "## Выходы" : "## Outputs");
            foreach (var p in desc.Outputs)
                sb.AppendLine($"- **`{p.Label}`** (`{p.DataType}`) — {p.Description ?? "—"}");
            sb.AppendLine();
        }

        if (desc.Parameters.Count > 0)
        {
            sb.AppendLine(isRu ? "## Параметры" : "## Parameters");
            foreach (var p in desc.Parameters)
            {
                var def = p.DefaultValue is null or "" ? "" : $" *(default: `{p.DefaultValue}`)*";
                sb.AppendLine($"- **{p.Label}** (`{p.Key}`){def} — {p.Description ?? "—"}");
            }
            sb.AppendLine();
        }

        sb.AppendLine(isRu
            ? "> *Автоматическая справка по метаданным узла (файл документации `.md` для этого плагина не предоставлен).*"
            : "> *Auto-generated reference from node metadata (no Markdown documentation file was provided by this plugin).*");

        return sb.ToString();
    }

    // --- JSON DTOs for strings.json ---

    private sealed class LocaleStringsBundle
    {
        [JsonPropertyName("categories")]
        public Dictionary<string, string>? Categories { get; set; }

        [JsonPropertyName("nodes")]
        public Dictionary<string, NodeLocaleEntry>? Nodes { get; set; }
    }

    private sealed class NodeLocaleEntry
    {
        [JsonPropertyName("displayName")]
        public string? DisplayName { get; set; }

        [JsonPropertyName("description")]
        public string? Description { get; set; }

        [JsonPropertyName("ports")]
        public Dictionary<string, PortLocaleEntry>? Ports { get; set; }

        [JsonPropertyName("parameters")]
        public Dictionary<string, ParamLocaleEntry>? Parameters { get; set; }
    }

    private sealed class PortLocaleEntry
    {
        [JsonPropertyName("label")]
        public string? Label { get; set; }

        [JsonPropertyName("description")]
        public string? Description { get; set; }
    }

    private sealed class ParamLocaleEntry
    {
        [JsonPropertyName("label")]
        public string? Label { get; set; }

        [JsonPropertyName("description")]
        public string? Description { get; set; }

        [JsonPropertyName("placeholder")]
        public string? Placeholder { get; set; }

        [JsonPropertyName("options")]
        public Dictionary<string, string>? Options { get; set; }
    }
}
